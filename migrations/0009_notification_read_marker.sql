-- 알림 (헤더 종 아이콘).
--
-- 알림을 위한 표를 따로 만들지 않는다. 알릴 일이 이미 `wiki_edits`에 전부 적혀 있기
-- 때문이다 — 내 편집이 검토를 받으면 `reviewed_at`이 찍히고, 운영자가 볼 제안은
-- `status = 'pending'`으로 남는다. 여기에 표를 더하면 같은 사실이 두 곳에 적히고,
-- 둘이 어긋나면 무엇이 맞는지 판정할 근거가 없다.
--
-- 그래서 저장하는 것은 사건이 아니라 **어디까지 봤는가** 하나뿐이다.
-- 읽지 않은 알림 = 이 시각 이후에 생긴 사건. NULL이면 아직 한 번도 열지 않은 것이다.
--
-- 이 방식의 대가를 적어 둔다. 알림을 하나씩 읽음 처리할 수 없고, 알림 화면을 열면
-- 그 시점까지가 통째로 읽음이 된다. 알림의 종류가 둘뿐인 지금은 이것으로 충분하고,
-- 종류가 늘어 개별 읽음이 필요해지면 그때 사건 표를 만든다.
ALTER TABLE users ADD COLUMN notifications_read_at TEXT;
