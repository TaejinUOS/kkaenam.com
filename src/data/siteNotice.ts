/**
 * 사이트 전체에 한 줄로 뜨는 공지.
 *
 * 지금은 **한 번에 하나만** 둔다. 공지가 여럿 겹치면 어느 것도 읽히지 않고, 헤더
 * 아래 한 줄은 그만큼 비싼 자리다. 새 공지를 낼 때는 아래 값을 갈아 끼운다.
 *
 * `id`를 바꾸는 것이 중요하다. 닫음 표시가 이 값으로 저장되므로, 값이 그대로면
 * 지난 공지를 닫은 사람에게 새 공지가 보이지 않는다. 날짜를 접두사로 두는 것은
 * 그래야 갈아 끼울 때 바꾸는 것을 잊지 않기 때문이다.
 *
 * 공지를 내릴 때는 `ACTIVE_NOTICE`를 `null`로 둔다.
 *
 * 서버(닫음 쿠키 비교)와 클라이언트(배너 그리기)가 같은 값을 봐야 해서 데이터만
 * 담은 모듈로 뺐다.
 */

export type SiteNotice = {
  /** 닫음 표시에 쓰는 값. 새 공지마다 반드시 바꾼다. */
  id: string;
  /** 왼쪽 딱지. 두세 글자. */
  label: string;
  body: string;
  /** 자세히 보기가 데려갈 곳. */
  href: string;
  linkLabel: string;
};

